#include "ThreadPoolTest100.h"

#include "Engine/Jobs/ThreadPool.h"

#include <atomic>

/**
 * @brief Проверяет базовую корректность выполнения задач ThreadPool.
 *
 * Тест создаёт ThreadPool с четырьмя worker-потоками
 * и ставит в очередь 100 независимых задач.
 *
 * Каждая задача атомарно увеличивает общий counter на 1.
 *
 * После постановки всех задач вызывается WaitIdle(),
 * поэтому проверка итогового значения выполняется
 * только после завершения всей очереди.
 *
 * Использование std::atomic<int> необходимо,
 * поскольку несколько worker-потоков
 * одновременно изменяют один и тот же counter.
 *
 * Тест проверяет, что:
 *
 * - все поставленные задачи были выполнены;
 * - WaitIdle() действительно ожидает их завершения;
 * - параллельное увеличение counter не приводит
 *   к потере обновлений.
 *
 * @return true, если после выполнения всех задач
 * counter равен 100.
 * @return false, если итоговое значение отличается.
 */
bool ThreadPoolTest::Run() {
	/**
	 * Создаём ThreadPool
	 * с четырьмя постоянными worker-потоками.
	 */
	ThreadPool pool(4);

	/**
	 * Общий счётчик изменяется
	 * из нескольких потоков одновременно,
	 * поэтому используется atomic.
	 */
	std::atomic<int> counter = 0;

	/**
	 * Ставим в очередь 100 независимых задач.
	 *
	 * Каждая задача увеличивает counter ровно на 1.
	 */
	for (int i = 0; i < 100; ++i) {
		pool.Enqueue([&counter] {
			counter.fetch_add(1);
		});
	}

	/**
	 * Ожидаем, пока очередь задач опустеет
	 * и все workers завершат текущую работу.
	 */
	pool.WaitIdle();

	/**
	 * При корректной работе ThreadPool
	 * каждая из 100 задач должна выполниться один раз.
	 */
	return counter.load() == 100;
}