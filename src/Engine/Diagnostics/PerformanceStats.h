#pragma once

#include <cstddef>

/**
 * @brief Хранит агрегированные показатели производительности Mini Engine.
 *
 * PerformanceStats используется для передачи результатов
 * измерения производительности между системой тестирования,
 * SceneViewport и пользовательским интерфейсом.
 *
 * Структура содержит:
 *
 * - количество объектов в тестовой сцене;
 * - количество worker-потоков;
 * - время CPU Update;
 * - время Render;
 * - общее время обработки кадра;
 * - вычисленное значение FPS.
 *
 * Все временные значения хранятся в миллисекундах.
 *
 * Структура содержит только данные и не выполняет
 * самостоятельных измерений или вычислений.
 */
struct PerformanceStats {
	/**
	 * @brief Количество объектов в тестовой сцене.
	 *
	 * Значение используется для фиксации размера нагрузки
	 * при сравнении различных режимов выполнения.
	 */
	std::size_t object_count = 0;

	/**
	 * @brief Количество worker-потоков.
	 *
	 * Для однопоточного режима значение обычно равно 1.
	 *
	 * В многопоточном режиме поле отражает количество workers,
	 * использованных при обработке сцены.
	 */
	std::size_t worker_count = 1;

	/**
	 * @brief Среднее время обновления CPU-логики сцены.
	 *
	 * Значение хранится в миллисекундах.
	 */
	double update_ms = 0.0;

	/**
	 * @brief Среднее время рендеринга кадра.
	 *
	 * Значение хранится в миллисекундах.
	 */
	double render_ms = 0.0;

	/**
	 * @brief Среднее полное время обработки кадра.
	 *
	 * Значение хранится в миллисекундах.
	 */
	double frame_ms = 0.0;

	/**
	 * @brief Производительность, выраженная в кадрах в секунду.
	 *
	 * Значение хранит FPS, рассчитанный системой тестирования
	 * на основе измеренного времени обработки кадра.
	 */
	double fps = 0.0;
};