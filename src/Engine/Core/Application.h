#pragma once

#include "Window.h"

/**
 * @brief Основной класс standalone-приложения Mini Engine.
 *
 * Application управляет жизненным циклом приложения:
 *
 * - создаёт главное окно;
 * - запускает главный цикл;
 * - обрабатывает обновление состояния;
 * - выполняет рендеринг кадра;
 * - завершает работу по запросу пользователя или окна.
 *
 * Класс владеет объектом Window и использует его
 * для взаимодействия с GLFW и OpenGL-контекстом.
 *
 * Application нельзя копировать.
 * Это предотвращает случайное дублирование состояния
 * приложения и объекта Window.
 */
class Application {
public:
    /**
     * @brief Создаёт объект приложения.
     *
     * Конструктор инициализирует внутренний Window.
     */
    Application();

    /**
     * @brief Уничтожает объект приложения.
     *
     * Освобождение ресурсов-членов класса
     * выполняется автоматически.
     */
    ~Application();

    /**
     * @brief Копирование Application запрещено.
     *
     * Объект приложения содержит состояние,
     * которое не должно дублироваться
     * через copy constructor.
     */
    Application(const Application&) = delete;

    /**
     * @brief Оператор копирующего присваивания запрещён.
     *
     * Это предотвращает копирование Window
     * и состояния выполнения приложения.
     */
    Application& operator=(const Application&) = delete;

    /**
     * @brief Запускает главный цикл приложения.
     *
     * Цикл выполняется до тех пор,
     * пока приложение не получит запрос на завершение.
     *
     * На каждой итерации выполняются:
     *
     * - обработка событий;
     * - Update();
     * - Render();
     * - обмен буферов окна.
     *
     * @return Код завершения приложения.
     */
    int Run();

private:
    /**
     * @brief Обновляет состояние приложения.
     *
     * В текущей реализации метод
     * обрабатывает пользовательский ввод,
     * влияющий на завершение основного цикла.
     */
    void Update();

    /**
     * @brief Выполняет отрисовку текущего кадра.
     *
     * Метод работает с активным OpenGL-контекстом
     * окна приложения.
     */
    void Render();

private:
    /**
     * @brief Главное окно приложения.
     *
     * Window управляет GLFWwindow
     * и связанным OpenGL-контекстом.
     */
    Window window_;

    /**
     * @brief Флаг выполнения основного цикла.
     *
     * Пока значение равно true,
     * Application::Run() продолжает работу,
     * если само окно также не запрошено на закрытие.
     */
    bool is_running_ = true;
};