#pragma once

/**
 * @brief Определяет режим выполнения CPU-логики Mini Engine.
 *
 * ExecutionMode используется для выбора способа обработки
 * вычислительной логики движка на центральном процессоре.
 *
 * Поддерживаются два режима:
 *
 * - SingleThreaded — выполнение логики в одном потоке;
 * - MultiThreaded — выполнение логики с использованием нескольких потоков.
 *
 * Перечисление применяется, в частности, при сравнении
 * однопоточного и многопоточного режимов обработки сцены
 * в нагрузочных тестах движка.
 *
 * Сам enum не содержит логики выполнения потоков.
 * Он только задаёт выбранную стратегию,
 * а конкретная реализация выполняется соответствующей
 * системой движка.
 */
enum class ExecutionMode {
	/**
	 * @brief Однопоточный режим выполнения.
	 *
	 * CPU-логика выполняется последовательно
	 * в текущем потоке без использования ThreadPool.
	 */
	SingleThreaded,

	/**
	 * @brief Многопоточный режим выполнения.
	 *
	 * CPU-логика может распределяться
	 * между несколькими worker-потоками.
	 */
	MultiThreaded
};