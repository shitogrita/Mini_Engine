#pragma once

#include "Engine/Math/matrix_types.h"

#include <vector>

/**
 * @brief Осево-ориентированный ограничивающий параллелепипед.
 *
 * BoundingBox хранит минимальную и максимальную точки геометрии
 * по осям X, Y и Z.
 *
 * Такая структура используется для быстрых пространственных проверок,
 * например при определении пересечения луча с объектом сцены.
 *
 * В текущей архитектуре BoundingBox хранится
 * в локальных координатах модели,
 * то есть до применения Transform объекта.
 */
struct BoundingBox {
    /**
     * @brief Минимальная точка BoundingBox.
     *
     * Содержит минимальные значения координат X, Y и Z.
     */
    Vec3 min{};

    /**
     * @brief Максимальная точка BoundingBox.
     *
     * Содержит максимальные значения координат X, Y и Z.
     */
    Vec3 max{};

    /**
     * @brief Создаёт BoundingBox, содержащий все переданные точки.
     *
     * Метод проходит по всему набору точек
     * и независимо для каждой координатной оси определяет:
     *
     * - минимальное значение;
     * - максимальное значение.
     *
     * Если points пуст,
     * возвращается BoundingBox{},
     * то есть коробка нулевого размера
     * с min = {0, 0, 0} и max = {0, 0, 0}.
     *
     * @param points Набор точек геометрии.
     *
     * @return BoundingBox, содержащий все переданные точки.
     */
    static BoundingBox FromPoints(const std::vector<Vec3>& points);

    /**
     * @brief Возвращает центр BoundingBox.
     *
     * Центр вычисляется как середина
     * между минимальной и максимальной точками:
     *
     * center = (min + max) / 2.
     *
     * @return Центр ограничивающего параллелепипеда.
     */
    Vec3 GetCenter() const;

    /**
     * @brief Возвращает размеры BoundingBox по трём осям.
     *
     * Размер вычисляется как:
     *
     * size = max - min.
     *
     * Компоненты результата соответствуют:
     *
     * - X — размеру по оси X;
     * - Y — размеру по оси Y;
     * - Z — размеру по оси Z.
     *
     * @return Размер BoundingBox.
     */
    Vec3 GetSize() const;
};