#pragma once

#include "Engine/Core/ExecutionMode.h"
#include "Engine/Jobs/ThreadPool.h"
#include "Engine/Scene/Scene.h"

/**
 * @brief Система CPU-обновления объектов сцены.
 *
 * SceneUpdateSystem отвечает за изменение состояния объектов Scene
 * перед этапом рендеринга.
 *
 * Система поддерживает два режима выполнения:
 *
 * ExecutionMode::SingleThreaded
 *     Все объекты обновляются последовательно главным потоком.
 *
 * ExecutionMode::MultiThreaded
 *     Объекты разбиваются на несколько диапазонов,
 *     после чего диапазоны передаются worker-потокам ThreadPool.
 *
 * В обоих режимах используется одна и та же функция UpdateObject().
 * Таким образом, отличается только способ выполнения вычислений,
 * а сама логика обновления объектов остаётся одинаковой.
 *
 * В этой системе не выполняются OpenGL-вызовы.
 * Рендеринг остаётся на основном Qt/OpenGL потоке.
 */
class SceneUpdateSystem {
public:
    /**
     * @brief Обновляет сцену в выбранном режиме выполнения.
     *
     * Метод является общей точкой входа для обновления Scene.
     * В зависимости от ExecutionMode управление передаётся либо
     * в UpdateSingleThreaded(), либо в UpdateMultiThreaded().
     *
     * @param scene Сцена, объекты которой необходимо обновить.
     * @param delta_time Время между текущим и предыдущим кадром в секундах.
     * @param mode Режим выполнения CPU-обновления.
     */
    void Update(Scene& scene, float delta_time, ExecutionMode mode);

    std::size_t GetWorkerCount() const;

private:
    /**
     * @brief Обновляет состояние одного объекта сцены.
     *
     * Эта функция содержит непосредственно вычислительную работу,
     * выполняемую для одного SceneObject.
     *
     * Именно она используется как в однопоточном, так и в
     * многопоточном режиме. Благодаря этому сравнение производительности
     * SingleThreaded и MultiThreaded остаётся корректным:
     * алгоритм одинаков, отличается только стратегия выполнения.
     *
     * Если MotionState объекта выключен, объект не изменяется.
     *
     * @param object Обновляемый объект сцены.
     * @param delta_time Время между кадрами в секундах.
     */
    void UpdateObject(SceneObject& object, float delta_time);

    /**
     * @brief Последовательно обновляет все объекты сцены.
     *
     * Все объекты обрабатываются одним потоком.
     * Этот режим используется как baseline для последующего
     * сравнения с многопоточным выполнением.
     *
     * @param scene Обновляемая сцена.
     * @param delta_time Время между кадрами в секундах.
     */
    void UpdateSingleThreaded(Scene& scene, float delta_time);

    /**
     * @brief Параллельно обновляет объекты сцены.
     *
     * Коллекция объектов разбивается на несколько диапазонов.
     * Каждый диапазон превращается в отдельную задачу ThreadPool.
     *
     * После постановки всех задач вызывается WaitIdle().
     * Поэтому метод завершится только тогда, когда все worker-потоки
     * закончат обновление своих объектов.
     *
     * Это гарантирует, что следующий этап — Render — начнётся уже после
     * завершения всех изменений Transform.
     *
     * @param scene Обновляемая сцена.
     * @param delta_time Время между кадрами в секундах.
     */
    void UpdateMultiThreaded(Scene& scene, float delta_time);

    /**
     * @brief Пул постоянных worker-потоков.
     *
     * Потоки создаются один раз вместе с SceneUpdateSystem
     * и затем переиспользуются на каждом кадре.
     *
     * Это значительно дешевле, чем создавать std::thread
     * заново для каждого кадра.
     */
    ThreadPool thread_pool_;
};