#pragma once

#include "../Math/matrix_types.h"

/**
 * @brief Представляет камеру трёхмерной сцены.
 *
 * Camera хранит положение и ориентацию камеры
 * в мировом пространстве.
 *
 * Ориентация задаётся двумя углами:
 *
 * - yaw — горизонтальный поворот;
 * - pitch — вертикальный поворот.
 *
 * На основе этих данных класс позволяет:
 *
 * - перемещать камеру вперёд и назад;
 * - выполнять боковое перемещение;
 * - перемещаться вдоль глобальной оси Y;
 * - изменять направление взгляда;
 * - получать локальный базис камеры;
 * - формировать View Matrix.
 *
 * View Matrix используется для преобразования координат:
 *
 * World Space -> Camera/View Space.
 */
class Camera {
public:
    /**
     * @brief Перемещает камеру вперёд
     * относительно текущего направления взгляда.
     *
     * Направление движения учитывает
     * текущие значения yaw и pitch.
     *
     * @param distance Расстояние перемещения.
     */
    void MoveForward(float distance);

    /**
     * @brief Перемещает камеру назад
     * относительно текущего направления взгляда.
     *
     * @param distance Расстояние перемещения.
     */
    void MoveBackward(float distance);

    /**
     * @brief Перемещает камеру влево
     * относительно её текущей ориентации.
     *
     * Для определения направления
     * используется локальный right-вектор камеры.
     *
     * @param distance Расстояние перемещения.
     */
    void MoveLeft(float distance);

    /**
     * @brief Перемещает камеру вправо
     * относительно её текущей ориентации.
     *
     * @param distance Расстояние перемещения.
     */
    void MoveRight(float distance);

    /**
     * @brief Перемещает камеру вверх
     * вдоль глобальной оси Y.
     *
     * Вертикальное движение не зависит
     * от текущего pitch камеры.
     *
     * @param distance Расстояние перемещения.
     */
    void MoveUp(float distance);

    /**
     * @brief Перемещает камеру вниз
     * вдоль глобальной оси Y.
     *
     * @param distance Расстояние перемещения.
     */
    void MoveDown(float distance);

    /**
     * @brief Изменяет ориентацию камеры.
     *
     * yaw_delta_degrees изменяет горизонтальный угол,
     * а pitch_delta_degrees — вертикальный.
     *
     * В реализации pitch ограничивается диапазоном:
     *
     * [-89°, 89°]
     *
     * что предотвращает переворот камеры
     * через вертикальное направление.
     *
     * @param yaw_delta_degrees Изменение yaw в градусах.
     * @param pitch_delta_degrees Изменение pitch в градусах.
     */
    void Rotate(float yaw_delta_degrees, float pitch_delta_degrees);

    /**
     * @brief Возвращает View Matrix камеры.
     *
     * Матрица строится на основе:
     *
     * - position_;
     * - forward-вектора;
     * - right-вектора;
     * - up-вектора.
     *
     * View Matrix преобразует координаты:
     *
     * World Space -> Camera/View Space.
     *
     * @return Матрица вида камеры.
     */
    Matrix4 GetViewMatrix() const;

    /**
     * @brief Возвращает текущую позицию камеры.
     *
     * @return Константная ссылка на position_.
     */
    const Vec3& GetPosition() const;

    /**
     * @brief Возвращает текущий горизонтальный угол камеры.
     *
     * @return Значение yaw в градусах.
     */
    float GetYaw() const;

    /**
     * @brief Возвращает текущий вертикальный угол камеры.
     *
     * @return Значение pitch в градусах.
     */
    float GetPitch() const;

    /**
     * @brief Возвращает направление взгляда камеры.
     *
     * Метод предоставляет вычисленный
     * нормализованный forward-вектор.
     *
     * @return Направление камеры вперёд.
     */
    Vec3 GetForward() const;

    /**
     * @brief Возвращает направление вправо
     * относительно камеры.
     *
     * Вектор перпендикулярен направлению взгляда
     * и используется для бокового перемещения.
     *
     * @return Нормализованный right-вектор камеры.
     */
    Vec3 GetRight() const;

    /**
     * @brief Возвращает локальное направление вверх камеры.
     *
     * Вектор строится на основе
     * текущих right и forward направлений
     * и является частью базиса камеры.
     *
     * @return Нормализованный up-вектор камеры.
     */
    Vec3 GetUp() const;

    /**
     * @brief Устанавливает позицию камеры
     * в мировом пространстве.
     *
     * @param position Новая позиция камеры.
     */
    void SetPosition(const Vec3& position);

private:
    /**
     * @brief Вычисляет нормализованное
     * направление взгляда камеры.
     *
     * Направление рассчитывается
     * на основе текущих yaw и pitch.
     *
     * @return Нормализованный forward-вектор.
     */
    Vec3 GetForwardDirection() const;

    /**
     * @brief Вычисляет нормализованное
     * направление вправо относительно камеры.
     *
     * Вектор получается через векторное произведение
     * forward-направления и глобального up-вектора.
     *
     * @return Нормализованный right-вектор.
     */
    Vec3 GetRightDirection() const;

    /**
     * @brief Горизонтальный угол поворота камеры в градусах.
     *
     * Начальное значение -90° соответствует
     * направлению взгляда вдоль отрицательной оси Z
     * при используемой формуле вычисления forward.
     */
    float yaw_degrees_ = -90.0f;

    /**
     * @brief Вертикальный угол поворота камеры в градусах.
     *
     * Начальное значение 0° означает
     * отсутствие вертикального наклона.
     */
    float pitch_degrees_ = 0.0f;

    /**
     * @brief Позиция камеры в мировом пространстве.
     *
     * Начальное положение:
     *
     * (0, 0, 3).
     */
    Vec3 position_{
        0.0f,
        0.0f,
        3.0f
    };
};