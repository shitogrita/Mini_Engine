#pragma once

#include "Engine/Assets/ImportedMaterialData.h"
#include "Engine/Assets/ImportedMeshData.h"

#include <string>
#include <vector>

/**
 * @brief Часть импортированной модели,
 * использующая один материал.
 *
 * ImportedMeshPart объединяет:
 *
 * - геометрию отдельной части модели;
 * - имя материала, назначенного этой геометрии.
 *
 * Такая структура позволяет одной импортированной модели
 * содержать несколько геометрических частей,
 * каждая из которых может использовать свой материал.
 */
struct ImportedMeshPart {
	/**
	 * @brief Геометрические данные части модели.
	 */
	ImportedMeshData mesh;

	/**
	 * @brief Имя материала,
	 * назначенного данной части геометрии.
	 *
	 * Значение соответствует имени материала,
	 * полученному из импортируемого файла модели.
	 */
	std::string material_name;
};

/**
 * @brief Полный промежуточный результат импорта модели.
 *
 * ImportedModelData хранит CPU-side данные,
 * полученные после разбора файла модели.
 *
 * Структура содержит:
 *
 * - геометрические части модели;
 * - импортированные материалы.
 *
 * Эти данные используются как промежуточное представление
 * между parser/importer-логикой
 * и созданием runtime-объектов движка.
 */
struct ImportedModelData {
	/**
	 * @brief Геометрические части импортированной модели.
	 *
	 * Каждая часть может ссылаться
	 * на отдельный материал через material_name.
	 */
	std::vector<ImportedMeshPart> meshes;

	/**
	 * @brief Материалы,
	 * прочитанные при импорте модели.
	 *
	 * Для OBJ-моделей эти данные могут быть получены
	 * из связанных MTL-файлов.
	 */
	std::vector<ImportedMaterialData> materials;
};