#pragma once

/**
 * @brief Фабрика геометрических примитивов Mini Engine.
 *
 * PrimitiveFactory отвечает за создание геометрических данных
 * стандартных примитивов движка.
 *
 * Результатом работы методов является ImportedMeshData,
 * содержащий подготовленное представление геометрии,
 * которое впоследствии может использоваться для создания Mesh.
 *
 * PrimitiveFactory не отвечает за:
 *
 * - создание SceneObject;
 * - создание OpenGL-ресурсов;
 * - загрузку моделей с диска;
 * - работу с Material;
 * - добавление объектов в Scene.
 *
 * Класс только формирует геометрические данные примитивов.
 */
class PrimitiveFactory {
public:
	/**
	 * @brief Создаёт геометрию плоскости.
	 *
	 * Метод формирует ImportedMeshData,
	 * описывающий стандартный примитив Plane.
	 *
	 * @return Геометрические данные созданной плоскости.
	 */
	static ImportedMeshData CreatePlane();

	/**
	 * @brief Создаёт геометрию куба.
	 *
	 * Метод формирует ImportedMeshData,
	 * описывающий стандартный примитив Cube.
	 *
	 * @return Геометрические данные созданного куба.
	 */
	static ImportedMeshData CreateCube();

	/**
	 * @brief Создаёт геометрию окружности.
	 *
	 * Метод формирует ImportedMeshData
	 * для примитива Circle.
	 *
	 * Параметры метода определяют характеристики
	 * создаваемой геометрии.
	 *
	 * @return Геометрические данные созданной окружности.
	 */
	static ImportedMeshData CreateCircle(...);
};