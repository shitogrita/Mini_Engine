#pragma once

#include "../Renderer/Vertex.h"

#include <cstdint>
#include <utility>
#include <vector>

/**
 * @brief Ребро Mesh, заданное индексами двух вершин.
 *
 * Первый и второй элементы pair содержат индексы
 * двух вершин, между которыми проходит ребро.
 *
 * Используется при хранении топологической информации
 * импортированной геометрии.
 */
using Edge = std::pair<std::uint32_t, std::uint32_t>;

/**
 * @brief Промежуточное представление геометрических данных импортированного Mesh.
 *
 * ImportedMeshData используется между этапом загрузки или генерации
 * геометрии и созданием OpenGL Mesh.
 *
 * Структура хранит как исходные геометрические данные,
 * полученные после импорта модели, так и данные,
 * подготовленные непосредственно для передачи Renderer.
 *
 * Это позволяет отделить:
 *
 * - чтение и разбор формата модели;
 * - хранение геометрии;
 * - подготовку Vertex;
 * - создание OpenGL Vertex Buffer Object;
 * - создание OpenGL Element Buffer Object.
 *
 * ImportedMeshData не владеет OpenGL-ресурсами.
 * Все данные находятся в оперативной памяти центрального процессора.
 *
 * После подготовки структура может быть передана в Mesh,
 * который создаёт необходимые OpenGL-буферы.
 */
struct ImportedMeshData {
    /**
     * @brief Позиции вершин исходной геометрии.
     *
     * Каждая позиция задаётся трёхмерным вектором Vec3
     * в локальном пространстве модели.
     *
     * Эти данные также могут использоваться для вычисления
     * BoundingBox объекта.
     */
    std::vector<Vec3> positions;

    /**
     * @brief Нормали вершин исходной геометрии.
     *
     * Нормали используются системой освещения
     * для вычисления взаимодействия поверхности со светом.
     *
     * Наличие данных определяется флагом has_normals.
     */
    std::vector<Vec3> normals;

    /**
     * @brief Текстурные координаты вершин.
     *
     * Каждая координата представлена Vec2
     * и используется для выборки цвета из Texture2D
     * внутри GLSL shader.
     *
     * Наличие данных определяется флагом has_tex_coords.
     */
    std::vector<Vec2> tex_coords;

    /**
     * @brief Цвета вершин.
     *
     * Содержит дополнительные цветовые данные,
     * если импортированная или сгенерированная геометрия
     * предоставляет цвет для отдельных вершин.
     *
     * Наличие данных определяется флагом has_colors.
     */
    std::vector<Color3> colors;

    /**
     * @brief Рёбра геометрии.
     *
     * Каждое ребро хранит индексы двух связанных вершин.
     *
     * Представление может использоваться для операций,
     * которым необходима информация о связях между вершинами,
     * независимо от итогового треугольного представления Mesh.
     */
    std::vector<Edge> edges;

    /**
     * @brief Индексы треугольников исходной геометрии.
     *
     * Каждые три последовательных индекса описывают
     * один треугольник.
     *
     * Индексы относятся к геометрическим данным,
     * сформированным на этапе импорта.
     */
    std::vector<std::uint32_t> tri_indices;

    /**
     * @brief Вершины, подготовленные для Renderer.
     *
     * В отличие от отдельных массивов positions,
     * normals, tex_coords и colors, этот массив
     * содержит уже собранные структуры Vertex.
     *
     * Именно render_vertices передаётся в Mesh
     * для создания OpenGL Vertex Buffer Object.
     */
    std::vector<Vertex> render_vertices;

    /**
     * @brief Индексы, подготовленные для индексированного рендеринга.
     *
     * Используются Mesh при создании OpenGL
     * Element Buffer Object.
     *
     * Renderer затем выполняет индексированную отрисовку
     * через glDrawElements() или glDrawElementsInstanced().
     */
    std::vector<std::uint32_t> render_indices;

    /**
     * @brief Указывает, содержит ли геометрия нормали.
     *
     * true означает, что массив normals содержит
     * корректные данные, полученные при импорте
     * или генерации геометрии.
     */
    bool has_normals = false;

    /**
     * @brief Указывает, содержит ли геометрия текстурные координаты.
     */
    bool has_tex_coords = false;

    /**
     * @brief Указывает, содержит ли геометрия цвета вершин.
     */
    bool has_colors = false;
};