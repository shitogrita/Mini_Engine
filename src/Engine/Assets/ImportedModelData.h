#pragma once

#include "ImportedMaterialData.h"
#include "ImportedMeshData.h"

#include <string>
#include <vector>

/**
 * @brief Описывает одну геометрическую часть импортированной модели.
 *
 * ImportedMeshPart связывает набор геометрических данных
 * с именем материала, который используется этой частью модели.
 *
 * Такое разделение необходимо для OBJ-моделей,
 * в которых разные группы полигонов могут использовать
 * разные материалы через директиву usemtl.
 *
 * В runtime-представлении Mini Engine каждая такая часть
 * может быть преобразована в отдельный SceneRenderPart,
 * содержащий собственные Mesh и Material.
 */
struct ImportedMeshPart {
    /**
     * @brief Геометрические данные части модели.
     *
     * Содержит вершины, индексы и дополнительные атрибуты,
     * подготовленные на этапе разбора импортируемой модели.
     *
     * Эти данные впоследствии используются
     * для создания runtime Mesh.
     */
    ImportedMeshData mesh;

    /**
     * @brief Имя материала, назначенного этой части модели.
     *
     * Значение соответствует имени материала,
     * указанному в OBJ через директиву usemtl.
     *
     * По этому имени ModelImporter находит
     * соответствующий ImportedMaterialData
     * в списке материалов ImportedModelData.
     */
    std::string material_name;
};

/**
 * @brief Полное промежуточное представление импортированной модели.
 *
 * ImportedModelData формируется после разбора OBJ
 * и связанного с ним MTL-файла.
 *
 * Структура объединяет:
 *
 * - геометрические части модели;
 * - материалы, доступные для этих частей.
 *
 * ImportedModelData является промежуточным уровнем между
 * файловыми parser-компонентами и runtime-объектами движка.
 *
 * После завершения импорта ModelImporter использует
 * эти данные для создания:
 *
 * - Mesh;
 * - Material;
 * - Texture2D;
 * - SceneRenderPart;
 * - SceneObject.
 *
 * Структура не владеет OpenGL-ресурсами
 * и содержит только данные в памяти центрального процессора.
 */
struct ImportedModelData {
    /**
     * @brief Геометрические части импортированной модели.
     *
     * Каждая часть содержит ImportedMeshData
     * и имя используемого материала.
     *
     * Если OBJ использует несколько материалов,
     * модель может содержать несколько ImportedMeshPart.
     */
    std::vector<ImportedMeshPart> meshes;

    /**
     * @brief Материалы, прочитанные из связанного MTL-файла.
     *
     * ModelImporter использует этот список,
     * чтобы по имени material_name каждой геометрической части
     * найти соответствующий ImportedMaterialData
     * и создать runtime Material.
     */
    std::vector<ImportedMaterialData> materials;
};