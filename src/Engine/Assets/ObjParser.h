#pragma once

#include "Engine/Assets/ImportedMeshData.h"
#include "Engine/Assets/ImportedModelData.h"

#include <string>

/**
 * @brief Выполняет разбор файлов формата Wavefront OBJ.
 *
 * ObjParser является частью системы импорта ресурсов Mini Engine
 * и преобразует текстовое представление OBJ
 * в промежуточные структуры данных движка.
 *
 * Парсер поддерживает основные геометрические директивы OBJ:
 *
 * - v — позиции вершин;
 * - vt — текстурные координаты;
 * - vn — нормали;
 * - f — полигоны;
 * - mtllib — подключение библиотеки материалов;
 * - usemtl — назначение материала геометрии.
 *
 * Поддерживаются различные варианты записи вершин полигона:
 *
 * - v;
 * - v/vt;
 * - v//vn;
 * - v/vt/vn.
 *
 * Также поддерживаются отрицательные OBJ-индексы.
 *
 * Полигоны с количеством вершин больше трёх
 * преобразуются в треугольники с помощью fan triangulation.
 *
 * ObjParser не создаёт runtime Mesh, Material или SceneObject.
 * Его задача заключается только в чтении файла
 * и формировании промежуточных структур ImportedMeshData
 * или ImportedModelData.
 *
 * Дальнейшее преобразование ImportedModelData
 * в объекты Renderer и Scene выполняется ModelImporter.
 */
class ObjParser {
public:
    /**
     * @brief Загружает OBJ как единый набор геометрических данных.
     *
     * Эта перегрузка предназначена для случаев,
     * когда информация о материалах и multipart-структура
     * модели не требуются.
     *
     * Во время разбора читаются:
     *
     * - позиции вершин;
     * - текстурные координаты;
     * - нормали;
     * - полигоны.
     *
     * На основе этих данных формируются:
     *
     * - edges;
     * - tri_indices;
     * - render_vertices;
     * - render_indices.
     *
     * Полигоны OBJ преобразуются в треугольники,
     * пригодные для индексированного рендеринга.
     *
     * Результат сохраняется в одном ImportedMeshData.
     *
     * @param filename Путь к OBJ-файлу.
     * @param mesh_data Структура, в которую записываются
     * разобранные геометрические данные.
     *
     * @return true, если после разбора была сформирована
     * пригодная для рендеринга геометрия; иначе false.
     */
    static bool Parse(const std::string& filename, ImportedMeshData& mesh_data);

    /**
     * @brief Загружает OBJ вместе с материалами
     * и multipart-структурой модели.
     *
     * Эта перегрузка используется ModelImporter
     * для полноценного импорта OBJ-моделей.
     *
     * Помимо геометрических директив,
     * она обрабатывает:
     *
     * - mtllib — подключение MTL-файлов;
     * - usemtl — назначение материала последующим полигонам.
     *
     * Геометрия разделяется на ImportedMeshPart
     * в зависимости от используемого материала.
     *
     * Если один и тот же material_name встречается
     * несколько раз через usemtl,
     * соответствующая геометрия добавляется
     * в уже существующий ImportedMeshPart.
     *
     * Для каждого material part формируется
     * собственный набор render_vertices
     * и render_indices.
     *
     * Материалы из подключённых MTL-файлов
     * сохраняются в ImportedModelData::materials.
     *
     * Путь к MTL разрешается относительно
     * директории OBJ-файла.
     *
     * @param filename Путь к OBJ-файлу.
     * @param model_data Структура, в которую записываются
     * геометрические части модели и импортированные материалы.
     *
     * @return true, если после разбора была получена
     * хотя бы одна пригодная для рендеринга
     * ImportedMeshPart; иначе false.
     */
    static bool Parse(const std::string& filename, ImportedModelData& model_data);
};