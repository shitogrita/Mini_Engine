#pragma once

#include "matrix_types.h"

/**
 * @brief Набор методов для построения матриц проекции Mini Engine.
 *
 * Projection содержит статические функции,
 * формирующие матрицы перспективной и ортографической проекции.
 *
 * Матрица проекции определяет,
 * каким образом координаты из camera/view space
 * преобразуются в пространство проекции.
 *
 * Поддерживаются:
 *
 * - перспективная проекция;
 * - произвольная ортографическая проекция;
 * - симметричная ортографическая проекция.
 *
 * Класс не хранит собственного состояния
 * и используется только через статические методы.
 */
class Projection {
public:
    /**
     * @brief Создаёт перспективную матрицу проекции.
     *
     * Perspective projection создаёт эффект перспективы:
     * объекты, расположенные дальше от камеры,
     * визуально уменьшаются.
     *
     * Матрица определяется:
     *
     * - вертикальным углом обзора;
     * - соотношением сторон viewport;
     * - ближней плоскостью отсечения;
     * - дальней плоскостью отсечения.
     *
     * @param fov_y_deg Вертикальный угол обзора в градусах.
     * @param aspect Соотношение ширины viewport к высоте.
     * @param z_near Расстояние до ближней плоскости отсечения.
     * @param z_far Расстояние до дальней плоскости отсечения.
     *
     * @return Матрица перспективной проекции.
     */
    static Matrix4 Perspective(float fov_y_deg, float aspect, float z_near, float z_far);

    /**
     * @brief Создаёт ортографическую матрицу проекции.
     *
     * В ортографической проекции размер объекта
     * не зависит от расстояния до камеры.
     *
     * Видимый объём задаётся шестью границами:
     *
     * - left;
     * - right;
     * - bottom;
     * - top;
     * - z_near;
     * - z_far.
     *
     * @param left Левая граница области проекции.
     * @param right Правая граница области проекции.
     * @param bottom Нижняя граница области проекции.
     * @param top Верхняя граница области проекции.
     * @param z_near Ближняя плоскость отсечения.
     * @param z_far Дальняя плоскость отсечения.
     *
     * @return Матрица ортографической проекции.
     */
    static Matrix4 Ortho(float left, float right, float bottom, float top, float z_near, float z_far);

    /**
     * @brief Создаёт симметричную ортографическую проекцию.
     *
     * Метод является удобной обёрткой над Ortho().
     *
     * Область проекции симметрично располагается
     * относительно начала координат:
     *
     * X: [-half_w, +half_w]
     *
     * Y: [-half_h, +half_h]
     *
     * @param half_w Половина ширины ортографической области.
     * @param half_h Половина высоты ортографической области.
     * @param z_near Ближняя плоскость отсечения.
     * @param z_far Дальняя плоскость отсечения.
     *
     * @return Матрица симметричной ортографической проекции.
     */
    static Matrix4 OrthoSymmetric(float half_w, float half_h, float z_near, float z_far);
};