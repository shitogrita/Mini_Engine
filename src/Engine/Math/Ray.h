#pragma once

#include "matrix_types.h"

struct BoundingBox;

/**
 * @brief Представляет луч в трёхмерном пространстве.
 *
 * Ray задаётся:
 *
 * - начальной точкой origin;
 * - направлением direction.
 *
 * Луч используется для пространственных запросов,
 * например для выбора объектов сцены
 * и проверки пересечения с BoundingBox.
 *
 * Положение точки на луче определяется формулой:
 *
 * P(t) = origin + direction * t
 */
struct Ray {
	/**
	 * @brief Начальная точка луча.
	 */
	Vec3 origin{};

	/**
	 * @brief Направление луча.
	 *
	 * Используется при вычислении точек на луче
	 * и проверке пространственных пересечений.
	 */
	Vec3 direction{};

	/**
	 * @brief Возвращает точку на луче
	 * на заданном расстоянии.
	 *
	 * Точка вычисляется по формуле:
	 *
	 * P(t) = origin + direction * t
	 *
	 * где distance соответствует параметру t.
	 *
	 * @param distance Расстояние вдоль направления луча.
	 *
	 * @return Точка на луче.
	 */
	Vec3 GetPoint(float distance) const;

	/**
	 * @brief Проверяет пересечение луча с BoundingBox.
	 *
	 * Метод определяет,
	 * существует ли пересечение луча
	 * с осево-ориентированным BoundingBox.
	 *
	 * Если пересечение найдено,
	 * в distance записывается расстояние
	 * до ближайшей точки пересечения
	 * в положительном направлении луча.
	 *
	 * Если начало луча уже находится внутри BoundingBox,
	 * distance соответствует точке выхода из коробки.
	 *
	 * @param box Проверяемый BoundingBox.
	 * @param distance Расстояние до точки пересечения.
	 *
	 * @return true, если луч пересекает BoundingBox;
	 * иначе false.
	 */
	bool Intersects(const BoundingBox& box, float& distance) const;
};