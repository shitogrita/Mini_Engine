#pragma once

#include <array>

/**
 * @brief Трёхмерный вектор.
 *
 * Vec3 используется для хранения значений,
 * состоящих из трёх компонент.
 *
 * В Mini Engine структура применяется, в частности, для:
 *
 * - позиции объекта;
 * - направления;
 * - масштаба;
 * - углов вращения;
 * - нормалей;
 * - RGB-значений.
 *
 * Все компоненты по умолчанию инициализируются нулём.
 */
struct Vec3 {
	/**
	 * @brief Компонента X.
	 */
	float x = 0.0f;

	/**
	 * @brief Компонента Y.
	 */
	float y = 0.0f;

	/**
	 * @brief Компонента Z.
	 */
	float z = 0.0f;
};

/**
 * @brief Четырёхкомпонентный вектор.
 *
 * Vec4 используется для хранения четырёх значений float.
 *
 * В зависимости от контекста компонента w может
 * использоваться как дополнительная координата
 * или однородная координата в математических вычислениях.
 *
 * Все компоненты по умолчанию инициализируются нулём.
 */
struct Vec4 {
	/**
	 * @brief Компонента X.
	 */
	float x = 0.0f;

	/**
	 * @brief Компонента Y.
	 */
	float y = 0.0f;

	/**
	 * @brief Компонента Z.
	 */
	float z = 0.0f;

	/**
	 * @brief Компонента W.
	 */
	float w = 0.0f;
};

/**
 * @brief Матрица размером 4x4.
 *
 * Matrix4 представлена как двумерный std::array
 * из 16 значений float.
 *
 * Доступ к элементам выполняется в формате:
 *
 * matrix[row][column].
 *
 * Тип используется для хранения матриц:
 *
 * - translation;
 * - rotation;
 * - scale;
 * - model transformation;
 * - обратных аффинных преобразований.
 *
 * Физически данные хранятся в виде массива строк,
 * а при необходимости передачи в API с column-major
 * представлением используется отдельное преобразование.
 */
using Matrix4 = std::array<std::array<float, 4>, 4>;