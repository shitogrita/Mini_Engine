#include "projection.h"

#include <cmath>

namespace {
    /**
     * @brief Число π, используемое для перевода градусов в радианы.
     */
    constexpr float kPi = 3.14159265358979323846f;
}

/**
 * @brief Создаёт перспективную матрицу проекции.
 *
 * Perspective projection используется для получения
 * визуального эффекта перспективы:
 *
 * - удалённые объекты выглядят меньше;
 * - близкие объекты выглядят больше.
 *
 * Матрица строится на основе:
 *
 * - вертикального угла обзора;
 * - соотношения сторон viewport;
 * - ближней плоскости отсечения;
 * - дальней плоскости отсечения.
 *
 * Угол обзора передаётся в градусах
 * и преобразуется в радианы перед вычислением tangent.
 *
 * @param fov_y_deg Вертикальный угол обзора в градусах.
 * @param aspect Соотношение ширины viewport к высоте.
 * @param z_near Расстояние до ближней плоскости отсечения.
 * @param z_far Расстояние до дальней плоскости отсечения.
 *
 * @return Матрица перспективной проекции.
 */
Matrix4 Projection::Perspective(float fov_y_deg, float aspect, float z_near, float z_far) {
    /**
     * Переводим вертикальный угол обзора
     * из градусов в радианы.
     */
    const float fov_rad = fov_y_deg * kPi / 180.0f;

    /**
     * Коэффициент перспективного масштабирования.
     *
     * Используется половина вертикального FOV.
     */
    const float f = 1.0f / std::tan(fov_rad * 0.5f);

    Matrix4 p{};

    /**
     * Масштабирование по оси X
     * дополнительно учитывает aspect ratio.
     */
    p[0][0] = f / aspect;
    p[0][1] = 0.0f;
    p[0][2] = 0.0f;
    p[0][3] = 0.0f;

    /**
     * Масштабирование по оси Y
     * определяется вертикальным field of view.
     */
    p[1][0] = 0.0f;
    p[1][1] = f;
    p[1][2] = 0.0f;
    p[1][3] = 0.0f;

    /**
     * Компоненты глубины преобразуют диапазон
     * между z_near и z_far в пространство проекции.
     */
    p[2][0] = 0.0f;
    p[2][1] = 0.0f;
    p[2][2] = (z_far + z_near) / (z_near - z_far);
    p[2][3] = (2.0f * z_far * z_near) / (z_near - z_far);

    /**
     * Значение -1 в p[3][2]
     * обеспечивает перспективное деление
     * после преобразования вершины.
     */
    p[3][0] = 0.0f;
    p[3][1] = 0.0f;
    p[3][2] = -1.0f;
    p[3][3] = 0.0f;

    return p;
}

/**
 * @brief Создаёт ортографическую матрицу проекции.
 *
 * Orthographic projection не использует перспективное уменьшение.
 *
 * Размер объекта на экране не зависит
 * от расстояния до камеры.
 *
 * Область видимости определяется шестью границами:
 *
 * - left;
 * - right;
 * - bottom;
 * - top;
 * - z_near;
 * - z_far.
 *
 * Матрица преобразует указанный ортографический объём
 * в стандартное пространство проекции.
 *
 * @param left Левая граница видимой области.
 * @param right Правая граница видимой области.
 * @param bottom Нижняя граница видимой области.
 * @param top Верхняя граница видимой области.
 * @param z_near Ближняя плоскость отсечения.
 * @param z_far Дальняя плоскость отсечения.
 *
 * @return Матрица ортографической проекции.
 */
Matrix4 Projection::Ortho(float left, float right, float bottom, float top, float z_near, float z_far) {
    Matrix4 o{};

    /**
     * Масштабирование и смещение по оси X.
     */
    o[0][0] = 2.0f / (right - left);
    o[0][1] = 0.0f;
    o[0][2] = 0.0f;
    o[0][3] = -(right + left) / (right - left);

    /**
     * Масштабирование и смещение по оси Y.
     */
    o[1][0] = 0.0f;
    o[1][1] = 2.0f / (top - bottom);
    o[1][2] = 0.0f;
    o[1][3] = -(top + bottom) / (top - bottom);

    /**
     * Масштабирование и смещение по оси Z
     * относительно ближней и дальней плоскостей.
     */
    o[2][0] = 0.0f;
    o[2][1] = 0.0f;
    o[2][2] = -2.0f / (z_far - z_near);
    o[2][3] = -(z_far + z_near) / (z_far - z_near);

    /**
     * Последняя строка сохраняет
     * стандартную аффинную форму преобразования.
     */
    o[3][0] = 0.0f;
    o[3][1] = 0.0f;
    o[3][2] = 0.0f;
    o[3][3] = 1.0f;

    return o;
}

/**
 * @brief Создаёт симметричную ортографическую проекцию.
 *
 * Метод является удобной обёрткой над Ortho().
 *
 * Видимая область симметрично располагается
 * относительно начала координат:
 *
 * X: [-half_w, +half_w]
 *
 * Y: [-half_h, +half_h]
 *
 * Параметры z_near и z_far передаются без изменения.
 *
 * @param half_w Половина ширины ортографической области.
 * @param half_h Половина высоты ортографической области.
 * @param z_near Ближняя плоскость отсечения.
 * @param z_far Дальняя плоскость отсечения.
 *
 * @return Симметричная ортографическая матрица проекции.
 */
Matrix4 Projection::OrthoSymmetric(float half_w, float half_h, float z_near, float z_far) {
    return Ortho(-half_w, +half_w, -half_h, +half_h, z_near, z_far);
}