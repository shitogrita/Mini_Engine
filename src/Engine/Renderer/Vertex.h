#pragma once

#include "../Math/matrix_types.h"

/**
 * @brief Двумерный вектор.
 *
 * Vec2 используется для хранения двухкомпонентных значений.
 *
 * В текущем renderer тип применяется
 * для хранения texture coordinates вершины.
 *
 * Все компоненты по умолчанию равны 0.
 */
struct Vec2 {
	/**
	 * @brief Компонента X.
	 */
	float x = 0.0f;

	/**
	 * @brief Компонента Y.
	 */
	float y = 0.0f;
};

/**
 * @brief RGB-цвет, состоящий из трёх float-компонент.
 *
 * Компоненты r, g и b по умолчанию равны 1.0f,
 * поэтому Color3{} представляет белый цвет.
 */
struct Color3 {
	/**
	 * @brief Красная компонента цвета.
	 */
	float r = 1.0f;

	/**
	 * @brief Зелёная компонента цвета.
	 */
	float g = 1.0f;

	/**
	 * @brief Синяя компонента цвета.
	 */
	float b = 1.0f;
};

/**
 * @brief Полный набор данных одной вершины Mesh.
 *
 * Vertex объединяет атрибуты,
 * передаваемые Renderer в vertex shader:
 *
 * - position — положение вершины;
 * - normal — нормаль поверхности;
 * - tex_coord — текстурные координаты;
 * - color — цвет вершины.
 *
 * В Mesh эти поля связываются
 * с соответствующими vertex attributes OpenGL.
 */
struct Vertex {
	/**
	 * @brief Позиция вершины в трёхмерном пространстве.
	 */
	Vec3 position{};

	/**
	 * @brief Нормаль вершины.
	 *
	 * Используется при расчёте освещения поверхности.
	 */
	Vec3 normal{};

	/**
	 * @brief Текстурные координаты вершины.
	 */
	Vec2 tex_coord{};

	/**
	 * @brief Цвет вершины.
	 *
	 * По умолчанию равен белому цвету,
	 * поскольку Color3 имеет значения (1, 1, 1).
	 */
	Color3 color{};
};